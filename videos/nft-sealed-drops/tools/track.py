"""Track things on screen so words can ride on them: python3 tools/track.py build/plain.mp4 → overlay/tracks.js

Positions are in output pixels (1920×1080), one sample per frame, as [t, x, y, w, h].
  robots: template matching from a starting box, the template refreshed as the robot changes
  paddles: the biggest bright blob near the last position (the white bidding paddles)
"""
import json
import os
import sys

import cv2
import numpy as np

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, HERE)
from timeline import FPS, START, END  # noqa: E402

VIDEO = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "build", "plain.mp4")
cap = cv2.VideoCapture(VIDEO)


def frames(t0, t1):
    cap.set(cv2.CAP_PROP_POS_FRAMES, int(round(t0 * FPS)))
    for i in range(int(round(t0 * FPS)), int(round(t1 * FPS))):
        ok, fr = cap.read()
        if not ok:
            return
        yield i / FPS, fr


def track_template(t0, t1, box, search=160, refresh=0.35):
    x, y, w, h = box
    out, tmpl = [], None
    for t, fr in frames(t0, t1):
        g = cv2.cvtColor(fr, cv2.COLOR_BGR2GRAY)
        if tmpl is None:
            tmpl = g[y:y + h, x:x + w].copy()
        else:
            sx0, sy0 = max(0, x - search), max(0, y - search)
            sx1, sy1 = min(g.shape[1], x + w + search), min(g.shape[0], y + h + search)
            area = g[sy0:sy1, sx0:sx1]
            if area.shape[0] > h and area.shape[1] > w:
                res = cv2.matchTemplate(area, tmpl, cv2.TM_CCOEFF_NORMED)
                _, _, _, loc = cv2.minMaxLoc(res)
                x, y = sx0 + loc[0], sy0 + loc[1]
                new = g[y:y + h, x:x + w]
                if new.shape == tmpl.shape:
                    tmpl = cv2.addWeighted(tmpl, 1 - refresh, new, refresh, 0)
        out.append([round(t, 4), int(x), int(y), int(w), int(h)])
    return smooth(out)


def track_bright(t0, t1, near, thresh=175, min_area=4000):
    cx, cy = near
    out = []
    for t, fr in frames(t0, t1):
        hsv = cv2.cvtColor(fr, cv2.COLOR_BGR2HSV)
        m = ((hsv[..., 2] > thresh) & (hsv[..., 1] < 70)).astype(np.uint8) * 255
        m = cv2.morphologyEx(m, cv2.MORPH_OPEN, np.ones((9, 9), np.uint8))
        n, lab, st, ce = cv2.connectedComponentsWithStats(m)
        best = None
        for i in range(1, n):
            if st[i, cv2.CC_STAT_AREA] < min_area:
                continue
            d = np.hypot(ce[i][0] - cx, ce[i][1] - cy)
            score = st[i, cv2.CC_STAT_AREA] / (1 + d / 120)
            if best is None or score > best[0]:
                best = (score, i)
        if best:
            i = best[1]
            x, y, w, h = st[i, :4]
            cx, cy = ce[best[1]]
            out.append([round(t, 4), int(x), int(y), int(w), int(h)])
        elif out:
            out.append([round(t, 4)] + out[-1][1:])
    return smooth(out)


def smooth(rows, k=3):
    if len(rows) < k:
        return rows
    a = np.array([r[1:] for r in rows], float)
    pad = np.vstack([a[:1].repeat(k // 2, 0), a, a[-1:].repeat(k // 2, 0)])
    sm = np.array([pad[i:i + k].mean(0) for i in range(len(a))])
    return [[rows[i][0]] + [int(v) for v in sm[i]] for i in range(len(rows))]


tracks = {
    # the lead robot as the snipers overtake the suits (the shot before is too blurred to track)
    "bot": track_template(START["6c"], END["6c"], (60, 280, 420, 560)),
}
path = os.path.join(HERE, "overlay", "tracks.js")
with open(path, "w") as f:
    f.write("// generated by tools/track.py\nwindow.TRACKS = " + json.dumps(tracks) + ";\n")
for k, v in tracks.items():
    print(k, len(v), v[:1], v[len(v) // 2:len(v) // 2 + 1], v[-1:])
